function detectBrowserLanguage(): Language {
  const browserLang = navigator.language?.split("-")[0]?.toLowerCase() || "fr";
  if (browserLang === "en") return "en";
  if (browserLang === "es") return "es";
  if (browserLang === "ar") return "ar";
  if (browserLang === "ru") return "ru";
  return "fr";
}

interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const LanguageContext = createContext<LanguageContextType>({
  language: "fr",
  setLanguage: () => {},
  t: (key) => key,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem("app_language") as Language;
    return saved && translations[saved] ? saved : detectBrowserLanguage();
  });
  const [profileSynced, setProfileSynced] = useState(false);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem("app_language", lang);
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.documentElement.lang = lang;
    // Save to profile in DB
    import("@/integrations/supabase/client").then(({ supabase }) => {
      supabase.auth.getUser().then(({ data }) => {
        if (data.user) {
          supabase.from("profiles").update({ preferred_language: lang } as any).eq("user_id", data.user.id).then(() => {});
        }
      });
    });
  };

  // Sync language from profile on auth change
  useEffect(() => {
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    document.documentElement.lang = language;

    import("@/integrations/supabase/client").then(({ supabase }) => {
      supabase.auth.getUser().then(({ data }) => {
        if (data.user && !profileSynced) {
          supabase.from("profiles").select("preferred_language").eq("user_id", data.user.id).single().then(({ data: profile }) => {
            if (profile?.preferred_language && translations[profile.preferred_language as Language]) {
              setLanguageState(profile.preferred_language as Language);
              localStorage.setItem("app_language", profile.preferred_language);
              document.documentElement.dir = profile.preferred_language === "ar" ? "rtl" : "ltr";
              document.documentElement.lang = profile.preferred_language;
            }
            setProfileSynced(true);
          });
        }
      });
    });
  }, []);

  const t = (key: string, vars?: Record<string, string | number>) => {
    let text = translations[language]?.[key] || translations.fr[key] || key;
    if (vars) {
      Object.entries(vars).forEach(([k, v]) => {
        text = text.replace(`{${k}}`, String(v));
      });
    }
    return text;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export const useLanguage = () => useContext(LanguageContext);
